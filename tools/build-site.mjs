// Writes assets/winch.js, the homepage's data, from content.json.
//   node tools/build-site.mjs
// content.json is the one content source for this site and the profile README (winchxyz/winchxyz).
// Sections keep their order there: Tools, Hermes plugins, Visual tools, then games; a section's
// "also" list becomes the Experiments line. Every project needs a 720x450 picture in assets/p/<id>.jpg
// unless it says "noimg" (draft-desk draws its three steps instead).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const content = JSON.parse(fs.readFileSync(path.join(ROOT, 'content.json'), 'utf8'));
const PICS = path.join(ROOT, 'assets', 'p');

/* colour and icon per section; the colours are the LED palette in assets/icons.js */
const CATS = {
  tools: { color: 'green', icon: 'wrench', unit: ['tool', 'tools'] },
  hermes: { color: 'blue', icon: 'plug', unit: ['plugin', 'plugins'] },
  visual: { color: 'magenta', icon: 'image', unit: ['tool', 'tools'] },
  games: { color: 'purple', icon: 'pad', unit: ['game', 'games'] },
  also: { color: 'grey', icon: 'flask', unit: ['project', 'projects'] },
};
/* the plugins' repos are hermes-*, the page names them without the prefix */
const NAMES = { 'hermes-x-bookmarks': 'x-bookmarks', 'hermes-ghost-call': 'ghost-call', 'hermes-phone': 'phone', 'hermes-blueprint': 'blueprint' };

const problems = [];
function project(id, cat) {
  const p = content.projects[id];
  if (!p) { problems.push(`${id}: listed in a section but missing from projects`); return null; }
  const pic = fs.existsSync(path.join(PICS, `${id}.jpg`));
  if (!pic && !p.noimg) problems.push(`${id}: no assets/p/${id}.jpg`);
  for (const k of ['short', 'stars', 'lang']) if (p[k] === undefined) problems.push(`${id}: no "${k}"`);
  return {
    id, cat,
    name: p.name || NAMES[id] || id,
    repo: id,
    short: p.short || '',
    line: p.line || p.short || '',
    live: p.live || null,
    code: `https://github.com/winchxyz/${id}`,
    label: p.label || (p.live ? 'Open' : 'Code'),
    stars: p.stars ?? null,
    lang: p.lang || null,
    img: pic && !p.noimg ? `assets/p/${id}.jpg` : null,
  };
}

const sections = [];
for (const s of content.sections) {
  if (!CATS[s.id]) problems.push(`section ${s.id}: no colour or icon in CATS`);
  sections.push({ id: s.id, title: s.title, line: s.line, ...CATS[s.id], items: s.ids.map(id => project(id, s.id)).filter(Boolean) });
  if (s.also) sections.push({
    id: 'also', title: 'Experiments', line: 'Graphics, sims and one-offs, mostly made in a day or two.',
    ...CATS.also, items: s.also.map(id => project(id, 'also')).filter(Boolean),
  });
}

const WINCH = {
  handle: 'winchxyz',
  line: content.line,
  stats: content.stats,
  links: { github: 'https://github.com/winchxyz', x: 'https://x.com/winchxyz', telegram: 'https://t.me/winchxyz' },
  sections,
};

if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const out = path.join(ROOT, 'assets', 'winch.js');
fs.writeFileSync(out, `/* Generated by tools/build-site.mjs from content.json. Edit content.json, not this file. */\nwindow.WINCH = ${JSON.stringify(WINCH, null, 1)};\n`);
const n = sections.reduce((a, s) => a + s.items.length, 0);
console.log(`assets/winch.js: ${sections.length} sections, ${n} projects, ${(fs.statSync(out).size / 1024).toFixed(1)} KB`);
